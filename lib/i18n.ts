const dictionaries: Record<Locale, Dictionary> = { en, zh, fr, es };

export function getDictionary(locale: Locale): Dictionary {
  return dictionaries[locale];
}

export async function getCookieLocale(): Promise<Locale> {
  const cookieStore = await cookies();
  return normalizeLocale(cookieStore.get(LOCALE_COOKIE)?.value);
}

export function htmlLanguage(locale: Locale): string {
  return locale === 'zh' ? 'zh-CN' : locale;
}

export function formatReplyLabel(count: number, locale: Locale): string {
  const dictionary = getDictionary(locale);
  return dictionary[count === 1 ? 'forum.replyOne' : 'forum.replyOther'];
}

export function formatRelativeTime(value: string, locale: Locale): string {
  const deltaSeconds = Math.round((Date.parse(value) - Date.now()) / 1000);
  const formatter = new Intl.RelativeTimeFormat(htmlLanguage(locale), { numeric: 'auto' });
  const ranges: Array<[Intl.RelativeTimeFormatUnit, number]> = [
    ['year', 60 * 60 * 24 * 365],
    ['month', 60 * 60 * 24 * 30],
    ['day', 60 * 60 * 24],
    ['hour', 60 * 60],
    ['minute', 60],
  ];
  for (const [unit, seconds] of ranges) {
    if (Math.abs(deltaSeconds) >= seconds) {
      return formatter.format(Math.round(deltaSeconds / seconds), unit);
    }
  }
  return formatter.format(deltaSeconds, 'second');
}
